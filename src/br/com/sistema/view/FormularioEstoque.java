    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed

        String descricao = txtDescricao.getText();
        Produtos obj = new Produtos();
        ProdutosDAO dao = new ProdutosDAO();
        Fornecedores f = new Fornecedores();
        FornecedoresDAO daof = new FornecedoresDAO();

        obj = dao.BuscarProdutos(descricao);
        if (obj.getDescricao() != null) {
            txtCodigo.setText(String.valueOf(obj.getId()));
            txtDescricao.setText(obj.getDescricao());
            txtQuantidadeAtual.setText(String.valueOf(obj.getPreco()));
            txtQuantidadeNova.setText(String.valueOf(obj.getQtdEstoque()));

            f = daof.BuscarFornecedor(obj.getFornecedores().getNome());

        } else {
            JOptionPane.showMessageDialog(null, "Produto não encontrado.");
        }
    }//GEN-LAST:event_btnPesquisarActionPerformed

