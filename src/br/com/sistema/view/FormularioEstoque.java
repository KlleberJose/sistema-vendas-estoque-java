    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        // TODO add your handling code here:
        try {

            int quantidadeAtual, quantidadeNova;
            quantidadeAtual = Integer.valueOf(txtQuantidadeAtual.getText());
            quantidadeNova = Integer.valueOf(txtQuantidadeNova.getText());

            qtd_atualizada = quantidadeAtual + quantidadeNova;
            ProdutosDAO daop = new ProdutosDAO();
            daop.adicionarEstoque(idProduto, qtd_atualizada);

            new Utilitarios().LimpaTela(painelEstoque);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Erro: " + e);
        }
    }//GEN-LAST:event_btnAdicionarActionPerformed

