    private void txtPesquisaProdutoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPesquisaProdutoKeyReleased
        // TODO add your handling code here:
        String descricao = "%" + txtPesquisaProduto.getText() + "%";

        ProdutosDAO dao = new ProdutosDAO();
        List<Produtos> lista = dao.Filtrar(descricao);

        DefaultTableModel dados = (DefaultTableModel) tabelaProduto.getModel();
        dados.setNumRows(0);

        for (Produtos p : lista) {
            dados.addRow(new Object[]{
                p.getId(),
                p.getDescricao(),
                p.getPreco(),
                p.getQtdEstoque(),
                p.getFornecedores().getNome()

            });
            txtCodigo.setEnabled(false);
        }
    }//GEN-LAST:event_txtPesquisaProdutoKeyReleased

    private void btnAdicionaItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionaItemActionPerformed
        // TODO add your handling code here:
        String nome = txtProduto.getText();
        Produtos obj = new Produtos();
        ProdutosDAO daop = new ProdutosDAO();

        obj = daop.BuscarProdutos(nome);

        if (obj.getDescricao() != null) {
            int estoque = Integer.valueOf(txtEstoque.getText());
            int quantidade = Integer.valueOf(txtQuantidade.getText());
            preco = Double.valueOf(txtPreco.getText());
            quantidade = Integer.valueOf(txtQuantidade.getText());
            subtotal = preco * quantidade;

            total += subtotal;

            if (estoque >= quantidade) {
                txtTotalVenda.setText(String.valueOf(total));
                meusProdutos = (DefaultTableModel) tabelaCarrinho.getModel();
                meusProdutos.addRow(new Object[]{
                    txtCodigo.getText(),
                    txtProduto.getText(),
                    txtQuantidade.getText(),
                    txtPreco.getText(),
                    subtotal
                });
            } else {
                JOptionPane.showMessageDialog(null, "A quantidade desejada é "
                        + "maior que o estoque.");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Não foi possível adicionar"
                    + " ao carrinho. Faltam informações ");
        }
    }//GEN-LAST:event_btnAdicionaItemActionPerformed

